-- Standalone ORACLE for six mandatory rule failures on synthetic Project A sample.
-- Tests detection queries only; does NOT prove Verity Hybrid rules were installed.
WITH S AS (SELECT * FROM VERITY_PILOT_A_DB.LAB.DQ_SIX_RULE_CASES)
SELECT
  COUNT(*) AS TOTAL,
  COUNT_IF(EVENT_ID IS NULL) AS NOT_NULL_FAIL,
  COUNT(ORDER_ID)-COUNT(DISTINCT ORDER_ID) AS UNIQUE_DUPLICATE_EXCESS,
  COUNT_IF(AGE IS NOT NULL AND (AGE < 0 OR AGE > 120)) AS RANGE_FAIL,
  COUNT_IF(TRIM(UPPER(ORDER_STATUS)) NOT IN ('ACTIVE','PENDING','CANCELLED')) AS VALUE_SET_FAIL,
  COUNT_IF(COUNTRY='IN' AND PHONE IS NULL) AS CONDITIONAL_REQUIRED_FAIL,
  COUNT_IF(ORDER_STATUS <> TRIM(ORDER_STATUS)) AS NO_EDGE_WHITESPACE_FAIL
FROM S;
